// Hard 中"必须含分数/小数步"手牌的占比
export const HARD_FRACTION_RATIO = 0.75

function classifyPools(target) {
  const easy = [], medium = [], fraction = [], division = []
  const combos = []
  ;(function gen2(start, depth, arr) {
    if (depth === 4) { combos.push([...arr]); return }
    for (let v = start; v <= 10; v++) { arr.push(v); gen2(v, depth + 1, arr); arr.pop() }
  })(1, 0, [])
  for (const h of combos) {
    const e = hasSolution(h, target, { allowOps: ['+', '-', '*'] })
    const int = hasSolution(h, target, { integerOnly: true })
    const solvable = hasSolution(h, target)
    if (e) easy.push(h)
    if (int) medium.push(h)
    if (solvable && !int) fraction.push(h)
    if (int && !e) division.push(h)
  }
  return { easy, medium, fraction, division }
}

const targetCache = new Map()

function poolsFor(target) {
  if (target === 24) {
    return { easy: EASY_POOL, medium: MEDIUM_POOL, fraction: FRACTION_POOL, division: DIVISION_POOL }
  }
  if (!targetCache.has(target)) targetCache.set(target, classifyPools(target))
  return targetCache.get(target)
}

// 按难度从已验证池发牌（随机仅决定抽哪副已验证的题）
export function dealHand(difficulty, target = 24, rand = Math.random) {
  const pools = poolsFor(target)
  if (difficulty === 'easy') {
    return [...pools.easy[Math.floor(rand() * pools.easy.length)]]
  }
  if (difficulty === 'hard') {
    const pool = rand() < HARD_FRACTION_RATIO ? pools.fraction : pools.division
    return [...pool[Math.floor(rand() * pool.length)]]
  }
  return [...pools.medium[Math.floor(rand() * pools.medium.length)]]
}
